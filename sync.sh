#!/bin/bash
# =============================================================================
# sync.sh — Ручная синхронизация SplitAndMerge → GitHub
# =============================================================================
# Контекст (для FreeBuff-агента в новой сессии):
#   - Проект: SplitAndMerge (редактура .docx + каскад фактчекинга)
#   - Remote:  https://github.com/DrHush47/SplitAndMerge
#   - Ветка:   main
#   - Режим:   только push (pull — вручную, через `git pull origin main`)
#
# Как вызвать:
#   bash sync.sh                          # авто-сообщение: "sync: ЧЧ:ММ ДД.ММ.ГГГГ"
#   bash sync.sh "обновил README и скрипты"  # твой текст добавится к дате
#
# Что делает:
#   1. Проверяет: есть ли незакоммиченные изменения (`git status --porcelain`)
#   2. Если изменений нет → выходит с сообщением «нечего пушить»
#   3. Если есть → git add -A, коммит с датой/временем, push
# =============================================================================

set -e  # упасть при любой ошибке (например, если нет сети)

# --- Шаг 1: проверить, есть ли изменения ------------------------------------
CHANGES=$(git status --porcelain 2>&1)

if [ -z "$CHANGES" ]; then
    echo "[sync] Изменений нет — пушить нечего."
    exit 0
fi

echo "[sync] Найдены изменения:"
echo "$CHANGES"
echo ""

# --- Шаг 2: добавить все файлы (с учётом .gitignore) ------------------------
git add -A

# --- Шаг 3: коммит ----------------------------------------------------------
TIMESTAMP=$(date "+%d.%m.%Y %H:%M")   # формат: 25.08.2026 14:30

if [ -n "$1" ]; then
    # пользователь передал описание — добавляем его после даты
    COMMIT_MSG="sync: $TIMESTAMP — $1"
else
    COMMIT_MSG="sync: $TIMESTAMP"
fi

git commit -m "$COMMIT_MSG"

# --- Шаг 4: push на GitHub --------------------------------------------------
git push origin main

echo ""
echo "[sync] Готово. Всё улетело на GitHub: $COMMIT_MSG"